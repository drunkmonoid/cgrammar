#!/usr/bin/env bash
# Regenerate INDEX.md: one line per example, taken from each file's header
# line "// NN_name.c - description" (or the first comment of a build.sh
# directory's script).
# Usage: scripts/make_index.sh > INDEX.md
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
shopt -s nullglob

echo "# Index of Examples"
echo
echo "Generated by \`scripts/make_index.sh\` from the header line of every example."
for chapter in [0-9][0-9]-*/; do
  chapter="${chapter%/}"
  title="$(sed -n '1s/^# //p' "$chapter/README.md")"
  echo
  echo "## [$title]($chapter/)"
  echo
  echo "| Example | Description |"
  echo "|---|---|"
  for f in "$chapter"/*.c "$chapter"/*.md "$chapter"/*/; do
    name="$(basename "$f")"
    [[ $name == README.md ]] && continue
    if [[ -d $f ]]; then
      [[ -f $f/build.sh ]] || continue
      desc="$(grep -m1 -E '^# ' "$f/build.sh" | sed 's/^# //')"
      name="$name/"
    elif [[ $name == *.md ]]; then
      desc="$(sed -n '1s/^# //p' "$f")"
    else
      desc="$(grep -m1 -F "// $name - " "$f" | sed "s|^// $name - ||")"
    fi
    echo "| [$name]($chapter/$name) | ${desc//|/\\|} |"
  done
done
